CREATE TABLE IF NOT EXISTS cars (
    id SERIAL PRIMARY KEY,
    status_id INTEGER NOT NULL,
    class_id INTEGER NOT NULL,
    model_id INTEGER NOT NULL,
    year_manufacture INTEGER NOT NULL CHECK (year_manufacture >= 1950),
    color VARCHAR(25),
    fuel_type_id INTEGER NOT NULL,
    engine_capacity DOUBLE PRECISION,
    transmission_id INTEGER NOT NULL,
    vehicle_drive_id INTEGER NOT NULL,
    current_mileage INTEGER DEFAULT 0 CHECK (current_mileage >= 0),
    maintenance_date DATE,
    air_conditioner BOOLEAN NOT NULL DEFAULT FALSE,
    heated_seats BOOLEAN NOT NULL DEFAULT FALSE,
    navigator BOOLEAN NOT NULL DEFAULT FALSE,
    options TEXT,

    FOREIGN KEY (status_id) REFERENCES statuses(id) ON DELETE CASCADE,
    FOREIGN KEY (class_id) REFERENCES service_classes(id) ON DELETE CASCADE,
    FOREIGN KEY (model_id) REFERENCES models(id) ON DELETE CASCADE,
    FOREIGN KEY (fuel_type_id) REFERENCES fuel_types(id) ON DELETE CASCADE,
    FOREIGN KEY (transmission_id) REFERENCES transmissions(id) ON DELETE CASCADE,
    FOREIGN KEY (vehicle_drive_id) REFERENCES vehicle_drives(id) ON DELETE CASCADE
    );

